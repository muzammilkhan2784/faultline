"""Plain-English briefings, composed from facts the graph already holds.

The UI shows numbers, tables and a graph. A first-time user still has to be
told what those *mean*. This module writes that explanation: what a function is,
what a change to it can reach, which tests cover it, and where the risk sits.

It is deliberately **templated, not generated by a language model**. Every
sentence is derived from a number or a flag in the graph, so a briefing can
never claim something the analysis did not find, and the same graph always
yields the same words -- which is what makes it unit-testable.

Nothing here touches a database. The route fetches; this module writes.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Literal

RiskLevel = Literal["low", "moderate", "high"]

# -- thresholds ---------------------------------------------------------------------------
# Named so the rules read as rules, and so the tests can pin them.

#: McCabe's bands. Above ``COMPLEX`` a function is hard to hold in your head.
SIMPLE_MAX_COMPLEXITY = 5
MODERATE_MAX_COMPLEXITY = 10
COMPLEX_MAX_COMPLEXITY = 20

#: A dependent this complicated is worth naming as a review priority.
FRAGILE_COMPLEXITY = 10

#: Path confidence below this is "probably", not "certainly".
UNCERTAIN_BELOW = 0.7

#: How many names to spell out before saying "and N more".
MAX_NAMES = 3

#: Risk points. ``reach`` is how many functions depend on the changed one.
FEW_DEPENDENTS = 5
MANY_DEPENDENTS = 20
MODERATE_FROM_POINTS = 2
HIGH_FROM_POINTS = 4

#: Share of dependents in one module before we call that module out.
CONCENTRATED_SHARE = 0.5
CONCENTRATED_MIN = 3


@dataclass(frozen=True, slots=True)
class Link:
    """A function mentioned in a paragraph, so the UI can make it clickable."""

    fqn: str
    label: str
    note: str


@dataclass(frozen=True, slots=True)
class Section:
    id: Literal["what", "affected", "tests", "risk"]
    title: str
    text: str
    """Prose. Names are wrapped in backticks so the UI can set them in code style."""
    links: tuple[Link, ...] = ()


@dataclass(frozen=True, slots=True)
class Briefing:
    fqn: str
    headline: str
    risk_level: RiskLevel
    sections: tuple[Section, ...]


@dataclass(frozen=True, slots=True)
class Notice:
    level: Literal["info", "warn"]
    text: str


@dataclass(frozen=True, slots=True)
class RepoOverview:
    text: str
    notices: tuple[Notice, ...]


# -- small text helpers -------------------------------------------------------------------


def plural(n: int, singular: str, many: str | None = None) -> str:
    """``1 function``, ``3 functions``, with thousands separators."""
    return f"{n:,} {singular if n == 1 else (many or singular + 's')}"


def agree(n: int, one: str, many: str) -> str:
    """Pick the verb form for a count: ``agree(1, "reaches", "reach")``."""
    return one if n == 1 else many


def plain(text: str) -> str:
    """Strip backticks: they are the UI's code markup, so stray ones would break it."""
    return text.replace("`", "'")


def code(text: str) -> str:
    """Mark text as a name, for the UI to set in monospace."""
    return "`" + plain(text) + "`"


def label_for(name: str, class_fqn: str | None) -> str:
    """``Flask.run`` for a method, ``run`` for a plain function."""
    return f"{class_fqn.rsplit('.', 1)[-1]}.{name}" if class_fqn else name


def name_list(labels: Sequence[str]) -> str:
    """``a, b and c``, or ``a, b, c and 4 more`` past ``MAX_NAMES``."""
    shown = [code(x) for x in labels[:MAX_NAMES]]
    extra = len(labels) - len(shown)
    if extra > 0:
        shown.append(f"{extra} more")
    if len(shown) <= 1:
        return "".join(shown)
    return ", ".join(shown[:-1]) + " and " + shown[-1]


def complexity_word(score: int) -> str:
    if score <= SIMPLE_MAX_COMPLEXITY:
        return "simple"
    if score <= MODERATE_MAX_COMPLEXITY:
        return "moderately complicated"
    if score <= COMPLEX_MAX_COMPLEXITY:
        return "complicated"
    return "very complicated"


def _is_untested(symbol: Mapping[str, Any], tests_total: int, repo_test_count: int | None) -> bool:
    """No test reaches it *and* testing was possible.

    A repository with no tests at all is a different problem, reported once at the
    repository level; it should not mark every function in it as individually risky.
    """
    return tests_total == 0 and repo_test_count != 0 and not symbol.get("is_test")


def _label(row: Mapping[str, Any]) -> str:
    return label_for(str(row["name"]), row.get("class_fqn"))


def _user_parameter_count(symbol: Mapping[str, Any]) -> int:
    """Parameters a caller supplies: ``self``/``cls`` is not one of them."""
    count = int(symbol.get("param_count") or 0)
    is_static = "staticmethod" in (symbol.get("decorators") or [])
    if symbol.get("is_method") and not is_static and count > 0:
        return count - 1
    return count


# -- the four sections ---------------------------------------------------------------------


def _what(symbol: Mapping[str, Any]) -> Section:
    name = _label(symbol)
    noun = "method" if symbol.get("is_method") else "function"
    if symbol.get("is_test"):
        kind = f"a test {noun}"
    elif symbol.get("is_async"):
        kind = f"an async {noun}"
    else:
        kind = f"a {noun}"
    if symbol.get("is_method") and symbol.get("class_fqn"):
        kind += f" of the class {code(str(symbol['class_fqn']).rsplit('.', 1)[-1])}"
    elif "<locals>" in str(symbol["fqn"]):
        kind += " defined inside another function"

    module = str(symbol.get("module") or symbol.get("module_fqn") or "")
    line = symbol.get("line_start")
    sentences = [
        f"{code(name)} is {kind}, found in {code(module)}" + (f" at line {line}." if line else ".")
    ]

    doc = symbol.get("doc")
    if doc:
        sentences.append(f"Its author describes it as: “{plain(str(doc))}”")
    else:
        sentences.append(
            "It has no docstring, so Faultline can describe its shape and connections "
            "but not its purpose; the source is the place to read what it is for."
        )

    params = _user_parameter_count(symbol)
    score = int(symbol.get("complexity") or 1)
    length = int(symbol.get("line_end") or 0) - int(line or 0) + 1
    shape = f"It takes {plural(params, 'parameter')}"
    if length > 0:
        shape += f" and is {plural(length, 'line')} long"
    shape += (
        f". Its complexity score is {score}, meaning {plural(score, 'independent path')} "
        f"through the code, which is {complexity_word(score)}."
    )
    sentences.append(shape)

    fan_out = int(symbol.get("fan_out") or 0)
    if fan_out:
        sentences.append(
            f"To do its job it calls {plural(fan_out, 'other function')} in this repository."
        )
    else:
        sentences.append(
            "It calls no other function in this repository: it does its work directly "
            "or through built-ins and libraries."
        )
    return Section("what", "What this function does", " ".join(sentences))


def _no_dependents(
    symbol: Mapping[str, Any], test_rows: Sequence[Mapping[str, Any]], min_confidence: float
) -> str:
    """Why nothing depends on this function, and what that does and does not mean."""
    name = code(_label(symbol))
    if symbol.get("is_test"):
        return (
            f"Nothing calls {name}, which is normal: it is a test, and the test runner "
            "starts it. Changing it only affects this one test."
        )
    if symbol.get("is_entrypoint"):
        return (
            f"Nothing else in this repository calls {name}, which is expected: it is an "
            "entry point, meaning the outside world (a web request, a command, a script "
            "being run) starts it. Changing it cannot break other code here, but it can "
            "change what users or callers outside the repository see."
        )
    hidden = int(symbol.get("fan_in") or 0)
    if hidden and not test_rows:
        return (
            f"At the current confidence filter ({min_confidence:.2f}) nothing is shown, but "
            f"Faultline did find {plural(hidden, 'possible caller')} that it is less sure of. "
            "Lower the confidence slider above the graph to see them."
        )
    if test_rows:
        return (
            f"No application code calls {name}. Only {plural(len(test_rows), 'test')} "
            f"{agree(len(test_rows), 'exercises', 'exercise')} it, so changing it cannot break "
            "other application code that Faultline can see, but it can break "
            f"{agree(len(test_rows), 'that test', 'those tests')}."
        )
    if symbol.get("is_private"):
        return (
            f"No function in this repository calls {name}. Its name starts with an "
            "underscore, which by convention marks an internal helper, so it may simply be "
            "unused. Check before deleting it, but changing it is unlikely to break anything."
        )
    return (
        f"No function in this repository calls {name}. That usually means one of three "
        "things: it is part of a public API used by other projects, it is called in a way "
        "static analysis cannot follow (a framework hook, a string lookup, a plug-in "
        "registry), or it is unused. Nothing visible breaks if you change it, but "
        "something invisible might."
    )


def _affected(
    symbol: Mapping[str, Any],
    prod: Sequence[Mapping[str, Any]],
    test_rows: Sequence[Mapping[str, Any]],
    depth: int,
    min_confidence: float,
) -> Section:
    title = "What is affected if you change it"
    name = code(_label(symbol))
    if not prod:
        return Section("affected", title, _no_dependents(symbol, test_rows, min_confidence))

    direct = [r for r in prod if r["distance"] == 1]
    indirect = len(prod) - len(direct)
    sentences = [
        f"If you change {name}, {plural(len(prod), 'other function')} can be affected "
        f"within {plural(depth, 'call')} of it."
    ]
    if direct:
        first = (
            f"{len(direct)} of them {agree(len(direct), 'calls', 'call')} it directly, so "
            f"{agree(len(direct), 'it is', 'they are')} the first to notice if what it "
            "accepts, returns or does changes"
        )
        if indirect:
            first += f"; the other {indirect} reach it through a chain of calls."
        else:
            first += "."
        sentences.append(first)
    else:
        sentences.append("None call it directly: every one reaches it through a chain of calls.")

    modules = Counter(str(r["module"]) for r in prod)
    top_module = modules.most_common(1)[0][0]
    if len(modules) == 1:
        sentences.append(f"All of them live in {code(top_module)}.")
    else:
        sentences.append(f"They are spread across {plural(len(modules), 'module')}.")

    entries = [r for r in prod if r.get("is_entrypoint")]
    if entries:
        verb = "is an entry point" if len(entries) == 1 else "are entry points"
        sentences.append(
            f"{len(entries)} of them {verb} ({name_list([_label(r) for r in entries])}): code "
            "that the outside world starts, such as a web route or a command, so a mistake "
            "here can reach real users."
        )
    return Section("affected", title, " ".join(sentences))


def _tests(
    symbol: Mapping[str, Any],
    tests: Sequence[Mapping[str, Any]],
    repo_test_count: int | None,
) -> Section:
    title = "Which tests to run"
    name = code(_label(symbol))
    if symbol.get("is_test"):
        return Section(
            "tests",
            title,
            f"{name} is itself a test. Run it directly; there is nothing to select.",
        )
    if not tests:
        if repo_test_count == 0:
            text = (
                "This repository has no tests that Faultline can recognise, so there is "
                "nothing to select. It looks for functions named `test_*` in files named "
                "`test_*.py` or `*_test.py`, or anywhere under a `tests/` folder. Until "
                "there are some, the only check is running the program yourself."
            )
        else:
            text = (
                f"No test reaches {name}, even indirectly, at the current confidence filter. "
                "Either it is untested, or a test reaches it in a way static analysis cannot "
                "see (a pytest fixture, a parametrised call, a mock). Run the full test suite "
                "to be safe, and consider writing a test for it."
            )
        return Section("tests", title, text)

    files = {str(t.get("path") or t.get("module")) for t in tests}
    nearest = min(tests, key=lambda t: (t["distance"], -float(t["confidence"])))
    hops = int(nearest["distance"])
    sentences = [
        f"{plural(len(tests), 'test')} can reach {name}, spread over {plural(len(files), 'file')}.",
        f"The closest is {code(str(nearest['name']))}, which is {plural(hops, 'call')} away, "
        "so start there.",
    ]
    uncertain = [t for t in tests if float(t["confidence"]) < UNCERTAIN_BELOW]
    if uncertain:
        sentences.append(
            f"{len(uncertain)} of them {agree(len(uncertain), 'reaches', 'reach')} it only "
            f"through links Faultline is less sure about (confidence under {UNCERTAIN_BELOW}), "
            f"so treat {agree(len(uncertain), 'that one', 'those')} as “probably”."
        )
    sentences.append(
        "Running only these tests is the fast check; the whole suite is the safe one. "
        "The Tests tab has a command you can copy."
    )
    return Section("tests", title, " ".join(sentences))


def _risk_level(
    symbol: Mapping[str, Any],
    prod: Sequence[Mapping[str, Any]],
    entries: Sequence[Mapping[str, Any]],
    tests_total: int,
    repo_test_count: int | None,
) -> RiskLevel:
    """Add up risk points: dependents, entry points, complexity, missing tests.

    This is a blast-radius rating, so a function nothing depends on is always low:
    however tangled it is inside, a change cannot spread.
    """
    reach = len(prod)
    if reach == 0:
        return "low"
    points = 1 if reach < FEW_DEPENDENTS else 2 if reach < MANY_DEPENDENTS else 3
    if entries:
        points += 1
    score = int(symbol.get("complexity") or 1)
    if score > COMPLEX_MAX_COMPLEXITY:
        points += 2
    elif score > MODERATE_MAX_COMPLEXITY:
        points += 1
    if _is_untested(symbol, tests_total, repo_test_count):
        points += 1
    if points >= HIGH_FROM_POINTS:
        return "high"
    if points >= MODERATE_FROM_POINTS:
        return "moderate"
    return "low"


def _risk(
    symbol: Mapping[str, Any],
    prod: Sequence[Mapping[str, Any]],
    tests_total: int,
    repo_test_count: int | None,
) -> Section:
    title = "Where the risk is concentrated"
    name = code(_label(symbol))
    score = int(symbol.get("complexity") or 1)
    links: list[Link] = []

    if not prod:
        text = (
            f"Very little can go wrong for other code: nothing that Faultline can see depends on "
            f"{name}. The remaining risk is inside the function itself (complexity {score}, "
            f"{complexity_word(score)}) and in callers that static analysis cannot see."
        )
        return Section("risk", title, text)

    sentences = [
        f"The risk comes from three things: how much depends on {name} "
        f"({plural(len(prod), 'function')}), how intricate it is (complexity {score}), and how "
        f"well tests cover it ({plural(tests_total, 'test')})."
    ]

    fragile = sorted(
        (r for r in prod if int(r.get("complexity") or 1) >= FRAGILE_COMPLEXITY),
        key=lambda r: (-int(r.get("complexity") or 1), int(r["distance"])),
    )
    if fragile:
        shown = fragile[:MAX_NAMES]
        sentences.append(
            f"Review these dependents first: {name_list([_label(r) for r in fragile])}. "
            "They are complicated (complexity 10 or more), so a change reaching them is the "
            "easiest to get subtly wrong."
        )
        links = [
            Link(
                fqn=str(r["fqn"]),
                label=_label(r),
                note=f"complexity {int(r.get('complexity') or 1)}, "
                f"{plural(int(r['distance']), 'call')} away",
            )
            for r in shown
        ]
    else:
        sentences.append(
            f"None of the {plural(len(prod), 'function')} that depend on it is especially "
            f"complicated (all under complexity {FRAGILE_COMPLEXITY}), so the risk is not "
            "concentrated in any one tangled spot: it comes from how many things depend on it."
        )

    modules = Counter(str(r["module"]) for r in prod)
    top_module, top_count = modules.most_common(1)[0]
    concentrated = top_count >= CONCENTRATED_MIN and top_count / len(prod) >= CONCENTRATED_SHARE
    if len(modules) > 1 and concentrated:
        sentences.append(
            f"Most of the exposure ({top_count} of {len(prod)}) sits in {code(top_module)}."
        )

    uncertain = [r for r in prod if float(r["confidence"]) < UNCERTAIN_BELOW]
    if uncertain:
        sentences.append(
            f"{len(uncertain)} of those connections "
            f"{agree(len(uncertain), 'is', 'are')} inferred rather than certain "
            f"(confidence under {UNCERTAIN_BELOW}), so check "
            f"{agree(len(uncertain), 'it is', 'they are')} real before you rely on "
            f"{agree(len(uncertain), 'it', 'them')}."
        )
    if _is_untested(symbol, tests_total, repo_test_count):
        sentences.append("No test reaches it, so a mistake would not be caught automatically.")
    return Section("risk", title, " ".join(sentences), tuple(links))


def _headline(
    level: RiskLevel,
    prod: Sequence[Mapping[str, Any]],
    entries: Sequence[Any],
    *,
    untested: bool,
) -> str:
    """One line that says the rating *and* what earned it, so it never looks arbitrary."""
    reach = len(prod)
    if reach == 0:
        return "Low risk: nothing else in this repository depends on it."
    dependents = plural(reach, "function") + (" depends" if reach == 1 else " depend")
    text = f"{level.capitalize()} risk: {dependents} on it"
    if entries and level == "high":
        text += f", including {plural(len(entries), 'entry point')}"
    if untested:
        text += ", and no test covers it"
    return text + "."


def build_briefing(
    symbol: Mapping[str, Any],
    impact: Sequence[Mapping[str, Any]],
    tests: Sequence[Mapping[str, Any]],
    *,
    depth: int,
    min_confidence: float,
    repo_test_count: int | None = None,
) -> Briefing:
    """Compose the four-paragraph briefing for one function.

    ``impact`` is what can reach the function within ``depth`` calls (tests
    included, as the impact endpoint returns them); ``tests`` is the wider test
    selection. ``repo_test_count`` is how many test functions the repository has
    at all, or ``None`` when unknown: it separates "untested" from "no tests exist".
    """
    prod = [r for r in impact if not r.get("is_test")]
    test_rows = [r for r in impact if r.get("is_test")]
    entries = [r for r in prod if r.get("is_entrypoint")]

    level = _risk_level(symbol, prod, entries, len(tests), repo_test_count)
    sections = (
        _what(symbol),
        _affected(symbol, prod, test_rows, depth, min_confidence),
        _tests(symbol, tests, repo_test_count),
        _risk(symbol, prod, len(tests), repo_test_count),
    )
    return Briefing(
        fqn=str(symbol["fqn"]),
        headline=_headline(
            level, prod, entries, untested=_is_untested(symbol, len(tests), repo_test_count)
        ),
        risk_level=level,
        sections=sections,
    )


# -- repository-level overview ---------------------------------------------------------------

#: Below this share of internal calls traced, impact results may under-count.
LOW_RESOLUTION = 0.6
LOW_RESOLUTION_MIN_CALLS = 20


def describe_repo(
    name: str,
    *,
    file_count: int,
    loc: int,
    counts: Mapping[str, int],
    internal_call_sites: int = 0,
    internal_resolution_rate: float = 0.0,
    parse_failures: int = 0,
) -> RepoOverview:
    """What was found in a repository, and what the numbers do (not) tell you."""
    functions = int(counts.get("functions", 0))
    classes = int(counts.get("classes", 0))
    calls = int(counts.get("call_edges", 0))
    tests = int(counts.get("test_functions", 0))

    text = (
        f"{code(name)} contains {plural(file_count, 'Python file')} "
        f"({loc:,} lines), which define {plural(functions, 'function')} and "
        f"{plural(classes, 'class', 'classes')}. Faultline read every one and drew a map of "
        f"which function calls which: it found {plural(calls, 'call')} between them. "
        "Pick any function to see what would be affected if you changed it, which tests cover "
        "it, and where the risk sits."
    )
    if internal_call_sites:
        text += (
            f" Of the calls between this repository's own functions, "
            f"{internal_resolution_rate:.0%} were traced to a definite target."
        )

    notices: list[Notice] = []
    if file_count == 0:
        notices.append(
            Notice(
                "warn",
                "No Python files were found, so there is nothing to map. Faultline analyses "
                "Python (.py) files only.",
            )
        )
    elif functions == 0:
        notices.append(
            Notice(
                "warn",
                "This code defines no functions, only top-level statements, so there is no "
                "call graph to explore. Wrapping logic in functions gives Faultline "
                "something to connect.",
            )
        )
    elif calls == 0:
        notices.append(
            Notice(
                "warn",
                "Functions were found, but none of them call each other, so there are no "
                "connections to follow. This is common for a folder of independent scripts, "
                "or for code whose calls all go to libraries rather than to each other.",
            )
        )
    if (
        functions
        and calls
        and internal_call_sites >= LOW_RESOLUTION_MIN_CALLS
        and internal_resolution_rate < LOW_RESOLUTION
    ):
        notices.append(
            Notice(
                "warn",
                f"Only {internal_resolution_rate:.0%} of the calls between this repository's "
                "own functions could be traced. It probably leans on dynamic patterns "
                "(metaclasses, registries, getattr), so impact results may under-count.",
            )
        )
    if functions and tests == 0:
        notices.append(
            Notice(
                "info",
                "No tests were recognised, so “which tests to run” will always be empty. "
                "Faultline looks for `test_*` functions in `test_*.py` or `*_test.py` files, "
                "or anything under a `tests/` folder.",
            )
        )
    if parse_failures:
        notices.append(
            Notice(
                "warn",
                f"{plural(parse_failures, 'file')} could not be parsed (a syntax error, or "
                "syntax from a newer Python) and "
                f"{'is' if parse_failures == 1 else 'are'} missing from the map.",
            )
        )
    return RepoOverview(text=text, notices=tuple(notices))


def repo_card_notice(repo: Mapping[str, Any]) -> str | None:
    """A one-line warning for the repository list, from fields the list already has."""
    if repo.get("status") != "ready":
        return None
    if repo.get("file_count") == 0:
        return "No Python files found. Faultline analyses Python (.py) files only."
    if repo.get("node_count") is not None and repo.get("edge_count") == 0:
        return "No function calls found, so there are no connections to explore."
    return None
